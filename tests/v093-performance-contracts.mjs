#!/usr/bin/env node
import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { normalizeAssets } from "../scripts/normalize-assets.mjs";
import { compileChineseSource } from "../core/scripts/compile-chinese-source.mjs";
import { planDeck } from "../core/scripts/plan-deck.mjs";
import { createProjectState, transitionProjectState } from "../core/scripts/project-state.mjs";
import { validateSceneCss } from "../scripts/scene-project.mjs";

const dir = fs.mkdtempSync(path.join(os.tmpdir(), "mint-v093-"));
const here = path.dirname(fileURLToPath(import.meta.url));
const skillRoot = path.resolve(here, "..");
const source = path.join(dir, "input.md");
fs.writeFileSync(source, "# 周报\n- 覆盖面扩大到140个贷款页面\n- 分析深度扩展到成本费用\n- 每次运行全量复查并输出累计报告\n\n# 下一步\n首先做小额测试。其次扩大范围。最后决定推广。\n");
const first = normalizeAssets(source, dir);
const second = normalizeAssets(source, dir);
assert.equal(first.manifest.assets[0].cacheHit, false);
assert.equal(second.manifest.assets[0].cacheHit, true);
const map = compileChineseSource({ rawText: first.combinedText, sourceName: "normalized-source.md", schemaVersion: "0.9.3" });
assert.ok(map.sourceUnits.every((unit) => unit.assetId && unit.sourceRef.startsWith("ASSET:")));
const plan = planDeck({ outputMode: "creative-html", pageContract: { constraint: "minimum-needed" } }, map);
assert.ok(plan.managementClusters.length < map.sourceUnits.length, "管理问题聚合不得退化为一段一 Scene");
const parallel = map.semanticGraph.edges.filter((edge) => edge.relationType === "parallel");
assert.ok(parallel.length >= 1, "并列列表必须识别为并列");
assert.ok(map.semanticGraph.edges.some((edge) => edge.relationType === "sequence"), "首先其次最后必须识别为递进");
const state = createProjectState({ sourceSetHash: first.manifest.sourceSetHash, sceneOrder: plan.pageContracts.map((page) => page.id), clusters: plan.managementClusters });
assert.equal(state.structureState, "exploring");
assert.throws(() => transitionProjectState(state, "set-profile", { qaProfile: "publish" }), /frozen/);
const soft = transitionProjectState(state, "soft-freeze");
const frozen = transitionProjectState({ ...soft, openIssues: [] }, "freeze");
assert.equal(transitionProjectState(frozen, "content-change", { affectedSceneIds: [frozen.currentSceneOrder[0]] }).structureState, "frozen");
assert.equal(transitionProjectState(frozen, "structure-change", { affectedSceneIds: frozen.currentSceneOrder }).structureState, "soft-frozen");
assert.ok(validateSceneCss('[data-scene-id="MC-test"] .x { display:grid; }', "MC-test").length === 0);
assert.ok(validateSceneCss(".x { display:grid !important; }", "MC-test").length >= 1);
const project = path.join(dir, "project");
const run = (script, args) => spawnSync(process.execPath, [path.join(skillRoot, "scripts", script), ...args], { encoding: "utf8", maxBuffer: 20_000_000 });
const prepared = run("prepare-creative.mjs", [source, project]);
assert.equal(prepared.status, 0, prepared.stderr || prepared.stdout);
const firstState = JSON.parse(fs.readFileSync(path.join(project, "project-state.json"), "utf8"));
const firstOrder = firstState.currentSceneOrder;
for (const file of fs.readdirSync(path.join(project, "src", "scenes")).filter((name) => name.endsWith(".html"))) {
  const target = path.join(project, "src", "scenes", file);
  fs.writeFileSync(target, fs.readFileSync(target, "utf8").replace(' data-scene-status="placeholder"', ""));
}
assert.equal(run("validate-scene-project.mjs", [project]).status, 0);
assert.equal(run("assemble-creative-report.mjs", [project, path.join(project, "report.html")]).status, 0);
assert.equal(run("qa-creative-html.mjs", [path.join(project, "report.html"), path.join(project, "creative-brief.json"), path.join(project, "qa-report.json")]).status, 0);
fs.writeFileSync(source, fs.readFileSync(source, "utf8").replace("140个", "141个"));
const revised = run("prepare-creative.mjs", [source, project]);
assert.equal(revised.status, 0, revised.stderr || revised.stdout);
const revisedState = JSON.parse(fs.readFileSync(path.join(project, "project-state.json"), "utf8"));
assert.deepEqual(revisedState.currentSceneOrder, firstOrder, "文字修订后稳定 Scene ID 不得变化");
assert.ok(revisedState.affectedSceneIds.length >= 1 && revisedState.affectedSceneIds.length < revisedState.currentSceneOrder.length, "只允许受影响 Scene 失效");
assert.match(fs.readFileSync(path.join(project, "session-brief.md"), "utf8"), new RegExp(revisedState.affectedSceneIds[0]));
assert.equal(revisedState.pdfState, "stale");
console.log(JSON.stringify({ passed: true, assetsCached: true, clusters: plan.managementClusters.length, sourceUnits: map.sourceUnits.length, forwardPipeline: true, stableSceneIds: true, incrementalInvalidation: true, repositoryStateRecovery: true }, null, 2));
