import assert from "node:assert/strict";
import { validateInteractions, getField } from "../scripts/interaction-contract.mjs";
import { compileChineseSource } from '../core/scripts/compile-chinese-source.mjs';
const model = { atoms: { A1: "审核", A2: "发放" } };
const scene = { id: "MC-credit", sourceUnitRefs: ["SU-1"], relationTypes: ["sequence"] };
assert.deepEqual(validateInteractions(scene, model), []);
const mod = { id: "flow", type: "workflow", goal: "查看审核与发放的衔接", nodes: ["A1", "A2"].map(id => ({ id, fieldPath: `atoms.${id}`, sourceUnitRefs: ["SU-1"] })), edges: [{ id: "e1", from: "A1", to: "A2", relation: "sequence", directed: true, sourceUnitRefs: ["SU-1"] }], guidedViews: [{ nodeIds: ["A2", "A1"] }] };
scene.interactiveModules = [mod];
assert.deepEqual(validateInteractions(scene, model), []);
assert.equal(mod.edges.length, 1, "guide order must never create edges");
const check = mutate => { const copy = structuredClone(scene); mutate(copy); assert.ok(validateInteractions(copy, model).length); };
check(s => s.interactiveModules[0].nodes[0].fieldPath = "atoms.missing");
check(s => s.interactiveModules[0].edges[0].to = "missing");
check(s => s.interactiveModules[0].edges[0].sourceUnitRefs = []);
check(s => s.relationTypes = ["parallel"]);
check(s => s.interactiveModules[0].type = "dataflow");
assert.equal(getField(model, "__proto__.toString"), undefined);
const sequential=compileChineseSource({rawText:'处理团队首先核验资料。\n处理团队其次检查结果。\n处理团队最后完成归档。',sourceName:'raw.txt',schemaVersion:'0.9.3'});
assert.ok(sequential.semanticGraph.edges.some(e=>e.relationType==='sequence'));
const parallel=compileChineseSource({rawText:'一、系统支持读取。\n二、系统支持检索。\n三、系统支持下载。',sourceName:'raw.txt',schemaVersion:'0.9.3'});
assert.equal(parallel.semanticGraph.edges.filter(e=>e.relationType==='sequence').length,0);
console.log(JSON.stringify({ passed: true, optionalModel: true, invalidGraphCases: 5 }));
