import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { inlineAssets } from '../scripts/offline-assets.mjs';
import { promoteCandidate } from '../scripts/promote-candidate.mjs';
import { bindFields } from '../scripts/field-bindings.mjs';
import { spreadPorts, estimateCjkWidth } from '../scripts/graph-layout.mjs';
const dir = fs.mkdtempSync(path.join(os.tmpdir(),'mint-v010-assets-'));
fs.writeFileSync(path.join(dir,'logo.svg'), '<svg xmlns="http://www.w3.org/2000/svg" width="2" height="2"/>');
fs.writeFileSync(path.join(dir,'unused.svg'), 'unused');
let result = inlineAssets('<style>.a{background:url("logo.svg")}</style><img src="logo.svg"><script>const t=`<img src="${x}">`</script>',dir);
assert.equal(result.manifest.assets.length,1); assert.equal(result.manifest.errors.length,0);
assert.match(result.html,/data:image\/svg\+xml;base64/); assert.match(result.html,/\$\{x\}/);
assert.ok(inlineAssets('<img src="https://example.com/img.png">',dir).manifest.errors.length);
assert.ok(inlineAssets('<style>@import "missing.css";</style>',dir).manifest.errors.length);
assert.ok(inlineAssets('<img src="missing.png">',dir).manifest.errors.length);
const b = bindFields('<span data-edit-policy="editable" data-field-path="atoms.A1">旧名称</span>',{atoms:{A1:'新名称'}});
assert.equal(b.errors.length,0); assert.match(b.html,/新名称/);
assert.ok(bindFields('<span data-edit-policy="editable" data-field-path="atoms.X">a</span>',{atoms:{}}).errors.length);
const c = path.join(dir,'candidate'); fs.mkdirSync(c); fs.writeFileSync(path.join(c,'report.html'),'new'); fs.writeFileSync(path.join(dir,'report.html'),'old');
assert.throws(()=>promoteCandidate(c,dir,['report.html','missing.pdf']));
assert.equal(fs.readFileSync(path.join(dir,'report.html'),'utf8'),'old');
promoteCandidate(c,dir,['report.html']); assert.equal(fs.readFileSync(path.join(dir,'report.html'),'utf8'),'new');
assert.deepEqual(spreadPorts({x:0,y:0,width:100,height:100},'right',3),[{x:100,y:25},{x:100,y:50},{x:100,y:75}]);
assert.ok(estimateCjkWidth('中文',40)>estimateCjkWidth('ab',40));
console.log(JSON.stringify({passed:true,referencedAssetsOnly:true,failedCandidatePreserved:true,canonicalFields:true}));
